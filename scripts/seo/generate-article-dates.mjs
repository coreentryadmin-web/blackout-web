#!/usr/bin/env node
// Derives real, evidence-based per-article datePublished/dateModified for
// src/lib/learn/articles.ts from actual git history, instead of the single
// hand-set ARTICLE_DATE_PUBLISHED/ARTICLE_DATE_MODIFIED constants every
// article previously shared (see docs/audit/FINDINGS.md, 2026-08-08 entry).
//
// datePublished = the date of the earliest commit whose diff introduces that
//   article's `slug:` line (i.e. when the article was first added).
// dateModified  = the most recent date `git blame` attributes to ANY line
//   within that article's object block (slug line through the line before
//   the next article's slug line) — a real "this content last changed" date,
//   not a guess.
//
// Deliberately does NOT fabricate distinct dates where none exist: an
// article touched only once gets datePublished === dateModified, which is
// honest, not a bug.
//
// Usage: node scripts/seo/generate-article-dates.mjs > src/lib/learn/article-dates.ts
// Re-run whenever src/lib/learn/articles.ts changes and commit the output.

import { execSync } from "node:child_process";
import { readFileSync } from "node:fs";

const FILE = "src/lib/learn/articles.ts";

function sh(cmd) {
  return execSync(cmd, { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 });
}

const src = readFileSync(FILE, "utf8").split("\n");
const slugs = [];
src.forEach((line, i) => {
  const m = line.match(/^\s*slug: "([^"]+)"/);
  if (m) slugs.push({ slug: m[1], line: i + 1 });
});
slugs.forEach((s, i) => {
  s.endLine = i + 1 < slugs.length ? slugs[i + 1].line - 1 : src.length;
});

if (slugs.length === 0) {
  console.error(`No article slugs found in ${FILE} — refusing to emit an empty dates file.`);
  process.exit(1);
}

// datePublished: earliest commit that introduces each slug line.
const commits = sh(`git log --follow --format='%H|%ad' --date=short --reverse -- ${FILE}`)
  .trim()
  .split("\n")
  .filter(Boolean)
  .map((line) => {
    const [hash, date] = line.split("|");
    return { hash, date };
  });

const published = new Map();
for (const { hash, date } of commits) {
  let diff;
  try {
    diff = sh(`git show ${hash} -- ${FILE}`);
  } catch {
    continue;
  }
  for (const m of diff.matchAll(/^\+\s*slug: "([^"]+)"/gm)) {
    const slug = m[1];
    if (!published.has(slug)) published.set(slug, date);
  }
}

// dateModified: max git-blame date across each article's full line range.
const modified = new Map();
for (const s of slugs) {
  const blame = sh(`git blame --date=short -L ${s.line},${s.endLine} -- ${FILE}`);
  let max = "0000-00-00";
  for (const m of blame.matchAll(/\(\S[^)]*?(\d{4}-\d{2}-\d{2})\s+\d+\)/g)) {
    if (m[1] > max) max = m[1];
  }
  modified.set(s.slug, max);
}

const missingPublished = slugs.filter((s) => !published.has(s.slug));
if (missingPublished.length > 0) {
  console.error(
    `WARNING: no datePublished found via git history for: ${missingPublished.map((s) => s.slug).join(", ")} — falling back to dateModified for these.`,
  );
}

const entries = slugs.map((s) => {
  const dateModified = modified.get(s.slug);
  const datePublished = published.get(s.slug) ?? dateModified;
  return { slug: s.slug, datePublished, dateModified };
});

const lines = [
  "// AUTO-GENERATED by scripts/seo/generate-article-dates.mjs — DO NOT hand-edit.",
  "// Regenerate after any change to src/lib/learn/articles.ts:",
  "//   node scripts/seo/generate-article-dates.mjs > src/lib/learn/article-dates.ts",
  "//",
  "// Real per-article datePublished (first git commit introducing the article) and",
  "// dateModified (most recent git-blame date across the article's full block) —",
  "// derived from actual git history, not fabricated. See docs/audit/FINDINGS.md",
  "// (2026-08-08, uniform article dates finding) for why this replaced the single",
  "// shared ARTICLE_DATE_PUBLISHED/ARTICLE_DATE_MODIFIED constant.",
  "",
  "export type ArticleDateEntry = { datePublished: string; dateModified: string };",
  "",
  "export const ARTICLE_DATES: Record<string, ArticleDateEntry> = {",
  ...entries.map(
    (e) => `  "${e.slug}": { datePublished: "${e.datePublished}", dateModified: "${e.dateModified}" },`,
  ),
  "};",
  "",
];

process.stdout.write(lines.join("\n"));
