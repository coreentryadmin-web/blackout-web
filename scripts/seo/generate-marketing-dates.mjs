#!/usr/bin/env node
// Derives real, evidence-based lastModified dates for the marketing/legal
// pages in sitemap-urls.ts from actual git history, instead of the
// hand-maintained MARKETING_DATES map in sitemap-dates.ts.
//
// Mirrors scripts/seo/generate-article-dates.mjs's approach (already used for
// /learn/* articles) for the same reason: a hardcoded date map goes stale the
// moment content changes and nobody remembers to bump it. Confirmed live
// 2026-09-02 — the homepage's hardcoded MARKETING_DATES["/"] said 2026-08-02
// while its real last content change (PR #3307, the 7-product registry
// migration) landed 2026-09-02, a month later. A stale sitemap <lastmod> is a
// real signal to Googlebot that a page hasn't changed and doesn't need a
// recrawl — plausibly why a search-index snapshot was still serving the old
// 6-engine copy well after the live page was already correct.
//
// dateModified = the date of the most recent commit that touched the page's
//   own route file (git log -1 --format=%ad --date=short -- <file>).
//
// Scope, stated honestly (same limitation class as the article generator):
// this tracks the page's own route file only, not shared components/data it
// imports. A change that lands entirely in a shared file (e.g. a footer or
// nav component used across pages) would not bump that page's date here. If
// that turns out to matter in practice, widen PAGE_FILES to a list of paths
// per route rather than reach for `git log` across the whole component tree.
//
// Usage: node scripts/seo/generate-marketing-dates.mjs > src/lib/seo/marketing-dates.ts

import { execSync } from "node:child_process";

function sh(cmd) {
  return execSync(cmd, { encoding: "utf8" }).trim();
}

// path (as used in sitemap-urls.ts / MARKETING_DATES) -> its own route file.
const PAGE_FILES = {
  "/": "src/app/(marketing)/page.tsx",
  "/pricing": "src/app/(marketing)/pricing/page.tsx",
  "/faq": "src/app/(marketing)/faq/page.tsx",
  "/why-blackout": "src/app/(marketing)/why-blackout/page.tsx",
  "/methodology": "src/app/(marketing)/methodology/page.tsx",
  "/vs/others": "src/app/(marketing)/vs/others/page.tsx",
  "/tools/gamma-snapshot": "src/app/(marketing)/tools/gamma-snapshot/page.tsx",
  "/about": "src/app/(marketing)/about/page.tsx",
  "/contact": "src/app/(marketing)/contact/page.tsx",
  "/learn": "src/app/(marketing)/learn/page.tsx",
};

const entries = Object.entries(PAGE_FILES).map(([path, file]) => {
  const date = sh(`git log -1 --format=%ad --date=short -- "${file}"`);
  if (!date) {
    console.error(`WARNING: no git history found for ${file} (path ${path}) — refusing to guess.`);
    process.exit(1);
  }
  return { path, date };
});

const lines = [
  "// AUTO-GENERATED by scripts/seo/generate-marketing-dates.mjs — DO NOT hand-edit.",
  "// Regenerate after any change to a marketing/legal page's own route file:",
  "//   node scripts/seo/generate-marketing-dates.mjs > src/lib/seo/marketing-dates.ts",
  "//",
  "// Real per-page lastModified derived from each page's own route file's git",
  "// history, not a hand-maintained guess. Replaces the previous hardcoded",
  "// MARKETING_DATES map in sitemap-dates.ts, which went stale by a full month",
  "// on the homepage (see the script's own header comment for the evidence).",
  "// Scope: tracks the page's own route file only, not shared imports — see",
  "// the generator script if that limitation ever needs widening.",
  "",
  "export const MARKETING_DATES: Record<string, string> = {",
  ...entries.map((e) => `  "${e.path}": "${e.date}",`),
  "};",
  "",
];

process.stdout.write(lines.join("\n"));
